function slugOf(tag: string): string {
  return tag.replace(/^\w+:/, "").toLowerCase().trim();
}

/** "" when the country is unknown */
export function offCountryTagToFlag(tag: string | null | undefined): string {
  if (!tag) return "";
  const iso = OFF_SLUG_TO_ISO[slugOf(tag)];
  if (iso?.length !== 2) return "";
  const base = 0x1f1e6;
  return String.fromCodePoint(
    base + iso.charCodeAt(0) - 65,
    base + iso.charCodeAt(1) - 65,
  );
}

/** "united-states" -> "United States" */
export function offCountryTagToName(tag: string | null | undefined): string {
  if (!tag) return "";
  return slugOf(tag)
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}
